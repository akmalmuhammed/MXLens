import type { AnalysisResult } from "./types.ts";
import { defang } from "./lib/text.ts";

function cell(value: string): string {
    return value.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

/** A ticket-ready Markdown summary. Indicators are defanged so they are safe to paste. */
export function toMarkdown(result: AnalysisResult): string {
    const m = result.message;
    const lines: string[] = [];
    lines.push(`## MXLens verdict: ${result.verdictLabel} (risk ${result.riskScore}/100)`, "");
    for (const s of result.summary) lines.push(`- ${s}`);
    lines.push("", "| Field | Value |", "| --- | --- |");
    lines.push(`| Subject | ${cell(m.subject ?? "")} |`);
    lines.push(`| From | ${cell(m.from ? `${m.from.name ? m.from.name + " " : ""}<${defang(m.from.address)}>` : "")} |`);
    if (m.replyTo.length) lines.push(`| Reply-To | ${cell(m.replyTo.map((r) => defang(r.address)).join(", "))} |`);
    if (m.returnPath) lines.push(`| Return-Path | ${cell(defang(m.returnPath))} |`);
    lines.push(`| Date | ${cell(m.date ?? "")} |`);
    const a = result.authentication;
    lines.push(`| SPF / DKIM / DMARC | ${a.spf.result} / ${a.dkim.map((d) => d.result).join(", ") || "none"} / ${a.dmarc.result} |`);
    if (result.findings.length) {
        lines.push("", "### Findings", "", "| Severity | Rule | Finding | ATT&CK |", "| --- | --- | --- | --- |");
        for (const f of result.findings) {
            lines.push(`| ${f.severity} | ${f.ruleId} | ${cell(f.summary)} | ${f.attack.map((t) => t.id).join(", ")} |`);
        }
    }
    const ind = result.indicators;
    const iocs = [
        ...ind.urls.map((u) => ["URL", defang(u)]),
        ...ind.domains.map((d) => ["Domain", defang(d)]),
        ...ind.ips.map((i) => ["IP", i]),
        ...ind.sha256.map((h) => ["SHA-256", h]),
    ];
    if (iocs.length) {
        lines.push("", "### Indicators", "", "| Type | Value |", "| --- | --- |");
        for (const [t, v] of iocs.slice(0, 50)) lines.push(`| ${t} | ${cell(v)} |`);
    }
    if (result.coverage.skipped.length) {
        lines.push("", "### Not checked", "");
        for (const s of result.coverage.skipped) lines.push(`- ${s.check}: ${s.reason}`);
    }
    lines.push("", `_Generated by MXLens engine ${result.engineVersion} at ${result.analyzedAt}._`);
    return lines.join("\n");
}

function csvField(value: string): string {
    return /[",\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value;
}

/** Indicators as CSV (type,value,context), for SIEM or blocklist import. */
export function toCsv(result: AnalysisResult): string {
    const rows: string[][] = [["type", "value", "context"]];
    const ctx = `${result.verdict}; ${result.message.subject ?? ""}`;
    for (const u of result.indicators.urls) rows.push(["url", u, ctx]);
    for (const d of result.indicators.domains) rows.push(["domain", d, ctx]);
    for (const i of result.indicators.ips) rows.push(["ip", i, ctx]);
    for (const e of result.indicators.emails) rows.push(["email", e, ctx]);
    for (const h of result.indicators.sha256) rows.push(["sha256", h, ctx]);
    return rows.map((r) => r.map(csvField).join(",")).join("\n") + "\n";
}

function uuid(): string {
    if (globalThis.crypto?.randomUUID) return globalThis.crypto.randomUUID();
    return "10000000-1000-4000-8000-100000000000".replace(/[018]/g, (c) =>
        (Number(c) ^ (Math.random() * 16) >> (Number(c) / 4)).toString(16),
    );
}

function stixString(value: string): string {
    return value.replace(/\\/g, "\\\\").replace(/'/g, "\\'");
}

/**
 * A STIX 2.1 bundle with one indicator per URL, domain, IP and file hash.
 * Indicators are typed "malicious-activity" only when the verdict is malicious.
 */
export function toStix(result: AnalysisResult): Record<string, unknown> {
    const now = new Date().toISOString();
    const type = result.verdict === "malicious" ? "malicious-activity" : "anomalous-activity";
    const description = `MXLens ${result.verdictLabel.toLowerCase()} (risk ${result.riskScore}/100): ${result.message.subject ?? "(no subject)"}`;
    const objects: Record<string, unknown>[] = [];
    const add = (name: string, pattern: string) =>
        objects.push({
            type: "indicator",
            spec_version: "2.1",
            id: `indicator--${uuid()}`,
            created: now,
            modified: now,
            name,
            description,
            indicator_types: [type],
            pattern,
            pattern_type: "stix",
            valid_from: now,
            labels: ["phishing", "mxlens"],
        });
    for (const u of result.indicators.urls) add(`URL ${u}`, `[url:value = '${stixString(u)}']`);
    for (const d of result.indicators.domains) add(`Domain ${d}`, `[domain-name:value = '${stixString(d)}']`);
    for (const ip of result.indicators.ips) add(`IP ${ip}`, ip.includes(":") ? `[ipv6-addr:value = '${ip}']` : `[ipv4-addr:value = '${ip}']`);
    for (const h of result.indicators.sha256) add(`File ${h}`, `[file:hashes.'SHA-256' = '${h}']`);
    return { type: "bundle", id: `bundle--${uuid()}`, objects };
}
